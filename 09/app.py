"""Архів вигаданого чернівецького гурту. SQLite локально, PostgreSQL на Heroku."""
from contextlib import contextmanager
from functools import wraps
from pathlib import Path
import hmac
import os
import secrets
import sqlite3
from flask import Flask,abort,redirect,render_template,request,session,url_for
from werkzeug.security import check_password_hash

app=Flask(__name__)
app.secret_key=os.getenv("SECRET_KEY") or secrets.token_hex(32)
app.config.update(SESSION_COOKIE_HTTPONLY=True,SESSION_COOKIE_SAMESITE="Lax")

@contextmanager
def database():
    url=os.getenv("DATABASE_URL")
    if url:
        import psycopg
        from psycopg.rows import dict_row
        conn=psycopg.connect(url,row_factory=dict_row)
        key="INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    else:
        conn=sqlite3.connect(Path(__file__).with_name("music.sqlite"))
        conn.row_factory=sqlite3.Row
        key="INTEGER PRIMARY KEY"
    def query(sql,args=()):
        return conn.execute(sql.replace("?", "%s") if url else sql,args)
    try:
        query(f"CREATE TABLE IF NOT EXISTS albums(id {key},title TEXT NOT NULL,year INTEGER NOT NULL,notes TEXT NOT NULL)")
        query("CREATE TABLE IF NOT EXISTS migrations(id INTEGER PRIMARY KEY)")
        if query("INSERT INTO migrations VALUES (1) ON CONFLICT DO NOTHING").rowcount:
            query("INSERT INTO albums(title,year,notes) VALUES (?,?,?)",("Після останнього рейсу",2025,"Дебютний мініальбом. Запис гітари й вокалу в репетиційній кімнаті."))
        yield query
        conn.commit()
    finally:
        conn.close()

@app.before_request
def check_form():
    session.setdefault("csrf",secrets.token_urlsafe(24))
    if request.method=="POST" and not hmac.compare_digest(session["csrf"],request.form.get("csrf","")):
        abort(400)

def editor(view):
    @wraps(view)
    def guarded(*args,**kwargs):
        if not session.get("editor"):
            abort(403)
        return view(*args,**kwargs)
    return guarded

@app.get("/")
def home():
    with database() as q:
        albums=q("SELECT * FROM albums ORDER BY year DESC,title").fetchall()
    return render_template("page.html",page="home",albums=albums)

@app.get("/about")
def about():
    return render_template("page.html",page="about")

@app.get("/history")
def history():
    return render_template("page.html",page="history")

@app.route("/login",methods=["GET","POST"])
def login():
    if request.method=="POST":
        hashed=os.getenv("EDITOR_HASH","")
        if not hashed or not check_password_hash(hashed,request.form.get("password","")):
            abort(403)
        session.clear()
        session["editor"]=True
        return redirect(url_for("home"))
    return render_template("page.html",page="login")

@app.post("/logout")
def logout():
    session.clear()
    return redirect(url_for("home"))

def get_album(q,ident):
    row=q("SELECT * FROM albums WHERE id=?",(ident,)).fetchone()
    if row is None:
        abort(404)
    return row

@app.get("/albums/<int:ident>")
def album(ident):
    with database() as q:
        row=get_album(q,ident)
    return render_template("page.html",page="album",album=row)

@app.route("/albums/new",methods=["GET","POST"])
@app.route("/albums/<int:ident>/edit",methods=["GET","POST"])
@editor
def edit(ident=None):
    with database() as q:
        row=get_album(q,ident) if ident is not None else {}
        if request.method=="POST":
            title=request.form.get("title","").strip()
            year=request.form.get("year",type=int)
            notes=request.form.get("notes","").strip()
            if not title or not year or not 1900<=year<=2100 or not notes:
                abort(400)
            if ident is None:
                q("INSERT INTO albums(title,year,notes) VALUES (?,?,?)",(title,year,notes))
            else:
                q("UPDATE albums SET title=?,year=?,notes=? WHERE id=?",(title,year,notes,ident))
            return redirect(url_for("home"))
    return render_template("page.html",page="edit",album=row)

@app.post("/albums/<int:ident>/delete")
@editor
def delete(ident):
    with database() as q:
        get_album(q,ident)
        q("DELETE FROM albums WHERE id=?",(ident,))
    return redirect(url_for("home"))
